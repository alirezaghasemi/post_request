export interface CiWorkflowOptions {
  workflowName?: string;
  collectionFile: string;
  environmentFile?: string;
  dataFile?: string;
  iterations?: number;
  bail?: boolean;
  reporters?: string[];
  nodeVersion?: string;
}

export function generateGitHubActionsWorkflow(options: CiWorkflowOptions): string {
  const name = options.workflowName || 'DevPilot API Automation Tests';
  const nodeVer = options.nodeVersion || '20.x';
  const iterations = options.iterations || 1;
  const reporters = options.reporters && options.reporters.length > 0
    ? options.reporters.join(',')
    : 'cli,junit';

  const flags: string[] = [options.collectionFile];
  if (options.environmentFile) {
    flags.push(`-e ${options.environmentFile}`);
  }
  if (options.dataFile) {
    flags.push(`-d ${options.dataFile}`);
  }
  if (iterations > 1) {
    flags.push(`-n ${iterations}`);
  }
  if (options.bail) {
    flags.push('--bail');
  }
  flags.push(`--reporters ${reporters}`);
  flags.push('--reporter-junit-export ./test-results/junit.xml');
  flags.push('--reporter-json-export ./test-results/devpilot-report.json');

  const runCommand = `npx devpilot run ${flags.join(' ')}`;

  return `# Auto-generated by DevPilot API Studio
name: ${name}

on:
  push:
    branches: [ main, master, develop ]
  pull_request:
    branches: [ main, master, develop ]
  workflow_dispatch:

jobs:
  api-tests:
    name: Run DevPilot API Test Suite
    runs-on: ubuntu-latest

    steps:
      - name: Checkout Repository
        uses: actions/checkout@v4

      - name: Setup Node.js ${nodeVer}
        uses: actions/setup-node@v4
        with:
          node-version: '${nodeVer}'
          cache: 'npm'

      - name: Install Dependencies
        run: npm ci || npm install

      - name: Create Test Results Directory
        run: mkdir -p ./test-results

      - name: Execute DevPilot Headless CLI Runner
        run: ${runCommand}

      - name: Upload Test Results Artifacts
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: devpilot-test-reports
          path: ./test-results/
          retention-days: 14

      - name: Publish Test Summary
        if: always()
        uses: dorny/test-reporter@v1
        continue-on-error: true
        with:
          name: DevPilot Test Report
          path: ./test-results/junit.xml
          reporter: java-junit
`;
}
